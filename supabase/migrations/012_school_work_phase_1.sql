-- Backfill parent/student links from the existing parent_email convention.
insert into public.parent_student_links (school_id, parent_id, student_id)
select s.school_id, p.id, s.id
from public.students s
join public.profiles p
  on p.school_id = s.school_id
 and lower(trim(coalesce(p.email,''))) = lower(trim(coalesce(s.parent_email,'')))
where lower(coalesce(p.role,'')) = 'parent'
  and coalesce(p.is_active,true)
  and nullif(trim(coalesce(s.parent_email,'')), '') is not null
on conflict (parent_id, student_id) do nothing;

create or replace function private.parent_can_access_student(p_student_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.students s
    where s.id = p_student_id
      and s.school_id = (select private.current_school_id())
      and (
        exists (
          select 1
          from public.parent_student_links l
          where l.school_id = s.school_id
            and l.student_id = s.id
            and l.parent_id = (select auth.uid())
        )
        or lower(trim(coalesce(s.parent_email,''))) =
           lower(trim(coalesce((select auth.jwt()->>'email'),'')))
      )
  )
$$;

create or replace function private.parent_can_access_class(p_class text, p_section text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.students s
    where s.school_id = (select private.current_school_id())
      and lower(trim(coalesce(s.class_name,''))) = lower(trim(coalesce(p_class,'')))
      and (
        nullif(trim(coalesce(p_section,'')), '') is null
        or lower(trim(coalesce(s.section_name,''))) = lower(trim(coalesce(p_section,'')))
      )
      and (select private.parent_can_access_student(s.id))
  )
$$;

create or replace function private.parent_can_access_assignment(p_assignment_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.assignments a
    where a.id = p_assignment_id
      and a.school_id = (select private.current_school_id())
      and (
        (
          coalesce(a.audience,'class') = 'class'
          and (select private.parent_can_access_class(a.assigned_class, a.assigned_section))
        )
        or
        (
          a.audience = 'students'
          and exists (
            select 1
            from public.assignment_students x
            where x.assignment_id = a.id
              and x.school_id = a.school_id
              and (select private.parent_can_access_student(x.student_id))
          )
        )
      )
  )
$$;

-- Replace the assignment SELECT policy so student-targeted work is not visible
-- to parents whose children are only classmates of the target student.
drop policy if exists assignments_select_role_scoped on public.assignments;
create policy assignments_select_role_scoped
on public.assignments
for select
to authenticated
using (
  (
    school_id = (select private.current_school_id())
    and (select private.is_school_admin())
  )
  or
  (
    school_id = (select private.current_school_id())
    and (select private."current_role"()) = 'teacher'
    and (
      created_by = (select auth.uid())
      or (select private.teacher_can_access_class(assignments.assigned_class, assignments.assigned_section))
    )
  )
  or
  (
    school_id = (select private.current_school_id())
    and (select private."current_role"()) = 'parent'
    and (select private.parent_can_access_assignment(assignments.id))
  )
);

