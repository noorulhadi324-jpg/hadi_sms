-- Keep links in sync when a student points at a parent email.
create or replace function public.sync_student_parent_link()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_parent_id uuid;
begin
  if nullif(trim(coalesce(new.parent_email,'')), '') is null then
    return new;
  end if;

  select p.id into v_parent_id
  from public.profiles p
  where p.school_id = new.school_id
    and lower(trim(coalesce(p.email,''))) = lower(trim(new.parent_email))
    and lower(coalesce(p.role,'')) = 'parent'
    and coalesce(p.is_active,true)
  limit 1;

  if v_parent_id is not null then
    insert into public.parent_student_links (school_id, parent_id, student_id)
    values (new.school_id, v_parent_id, new.id)
    on conflict (parent_id, student_id) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_sync_student_parent_link on public.students;
create trigger trg_sync_student_parent_link
after insert or update of parent_email, school_id
on public.students
for each row execute function public.sync_student_parent_link();

-- When a parent profile is created after the student, backfill all matching children.
create or replace function public.sync_parent_profile_children()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if lower(coalesce(new.role,'')) = 'parent'
     and coalesce(new.is_active,true)
     and new.school_id is not null
     and nullif(trim(coalesce(new.email,'')), '') is not null then
    insert into public.parent_student_links (school_id, parent_id, student_id)
    select s.school_id, new.id, s.id
    from public.students s
    where s.school_id = new.school_id
      and lower(trim(coalesce(s.parent_email,''))) = lower(trim(new.email))
    on conflict (parent_id, student_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_sync_parent_profile_children on public.profiles;
create trigger trg_sync_parent_profile_children
after insert or update of email, role, school_id, is_active
on public.profiles
for each row execute function public.sync_parent_profile_children();

