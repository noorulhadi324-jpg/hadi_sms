-- Phase 1: homework/assignment date ranges, targeted students, parent links,
-- and parent-specific work notifications.

alter table public.assignments
  add column if not exists work_type text not null default 'assignment',
  add column if not exists start_date date,
  add column if not exists audience text not null default 'class';

update public.assignments
set start_date = coalesce(start_date, assigned_date, current_date)
where start_date is null;

alter table public.assignments
  alter column start_date set default current_date;

alter table public.assignments
  alter column start_date set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'assignments_work_type_check'
      and conrelid = 'public.assignments'::regclass
  ) then
    alter table public.assignments
      add constraint assignments_work_type_check
      check (work_type in ('assignment','homework'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'assignments_audience_check'
      and conrelid = 'public.assignments'::regclass
  ) then
    alter table public.assignments
      add constraint assignments_audience_check
      check (audience in ('class','students'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'assignments_date_range_check'
      and conrelid = 'public.assignments'::regclass
  ) then
    alter table public.assignments
      add constraint assignments_date_range_check
      check (due_date is null or due_date >= start_date);
  end if;
end $$;

create index if not exists idx_assignments_school_type_dates
  on public.assignments (school_id, work_type, start_date, due_date);

