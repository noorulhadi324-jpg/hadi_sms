create or replace function public.refresh_school_work_parent_notifications(p_assignment_id bigint)
returns integer
language plpgsql
security definer
set search_path = public, private
set row_security = off
as $$
declare
  v_uid uuid := auth.uid();
  v_assignment public.assignments%rowtype;
  v_count integer := 0;
begin
  if v_uid is null then
    raise exception 'Not authenticated';
  end if;

  select * into v_assignment
  from public.assignments
  where id = p_assignment_id
    and school_id = private.current_school_id();

  if not found then
    raise exception 'School work record not found';
  end if;

  if not private.is_school_admin()
     and not (private."current_role"() = 'teacher' and v_assignment.created_by = v_uid) then
    raise exception 'Not authorized';
  end if;

  delete from public.parent_work_notifications
  where assignment_id = p_assignment_id;

  insert into public.parent_work_notifications (
    school_id, parent_id, student_id, assignment_id, title, message
  )
  select distinct
    v_assignment.school_id,
    l.parent_id,
    s.id,
    v_assignment.id,
    case when v_assignment.work_type = 'homework' then 'New Homework' else 'New Assignment' end,
    s.full_name || ' (' || coalesce(s.class_name,'') ||
      case when nullif(trim(coalesce(s.section_name,'')), '') is null then '' else '-' || s.section_name end ||
      ') received ' || coalesce(v_assignment.subject,'school work') || ': ' || v_assignment.title ||
      '. Due: ' || coalesce(to_char(v_assignment.due_date,'DD Mon YYYY'),'No due date')
  from public.students s
  join public.parent_student_links l
    on l.student_id = s.id and l.school_id = s.school_id
  where s.school_id = v_assignment.school_id
    and coalesce(s.is_active,true)
    and (
      (
        v_assignment.audience = 'class'
        and lower(trim(coalesce(s.class_name,''))) = lower(trim(coalesce(v_assignment.assigned_class,'')))
        and (
          nullif(trim(coalesce(v_assignment.assigned_section,'')), '') is null
          or lower(trim(coalesce(s.section_name,''))) = lower(trim(coalesce(v_assignment.assigned_section,'')))
        )
      )
      or
      (
        v_assignment.audience = 'students'
        and exists (
          select 1 from public.assignment_students x
          where x.assignment_id = v_assignment.id
            and x.student_id = s.id
            and x.school_id = v_assignment.school_id
        )
      )
    )
  on conflict (parent_id, student_id, assignment_id) do update
    set title = excluded.title,
        message = excluded.message,
        is_read = false,
        created_at = now();

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

grant execute on function public.refresh_school_work_parent_notifications(bigint) to authenticated;
